function study = runClassicJitterParameterStudy(cfg, lockedSelections)
%RUNCLASSICJITTERPARAMETERSTUDY 运行经典方法公平调参与锁定验证研究。
%   smokeStudy = runClassicJitterParameterStudy(config("smoke"), [])
%   preliminaryStudy = runClassicJitterParameterStudy( ...
%       config("preliminary"), smokeStudy.selections)
%
%   lockedSelections为空时，对config.m中的每个快拍数执行参数筛选，再调用
%   runClassicJitterSweep生成正式五方法结果。传入smoke阶段的锁定参数时，
%   本函数跳过筛选并直接验证，禁止依据preliminary结果再次调参。

arguments
    cfg (1,1) struct
    lockedSelections = []
end

cfg = uav.config.validate(cfg);
requiredMethods = ["oracle", "dl_mvdr", "esp", "wco", ...
    "static_incm_mvdr"];
configuredMethods = reshape(cfg.experiments.classicJitterMethodNames, 1, []);
if ~isequal(configuredMethods, requiredMethods)
    error('uav:experiment:ClassicParameterStudyMethodMismatch', ...
        '该参数研究要求方法顺序为Oracle、DL-MVDR、ESP、WCO和静态INCM。');
end
snapshotCounts = reshape(cfg.experiments.classicTuning.snapshotCounts, 1, []);
isValidationOnly = ~isempty(lockedSelections);
if isValidationOnly
    validateLockedSelections(lockedSelections, snapshotCounts);
end

scenarioTemplate = struct( ...
    'snapshotCount', NaN, ...
    'screening', [], ...
    'screeningArtifacts', struct(), ...
    'selection', struct(), ...
    'formalResult', struct(), ...
    'minimumIncmMedianSinrDb', NaN, ...
    'incmTargetMet', false, ...
    'incmDominatesPracticalMethodsAtEveryPoint', false);
scenarios = repmat(scenarioTemplate, 1, numel(snapshotCounts));
selections = repmat(emptySelection(), 1, numel(snapshotCounts));
comparisonTables = cell(1, numel(snapshotCounts));

for snapshotIndex = 1:numel(snapshotCounts)
    snapshotCount = snapshotCounts(snapshotIndex);
    fprintf('[经典参数研究] 开始profile=%s，L=%d。\n', cfg.profile, snapshotCount);
    if isValidationOnly
        selection = lockedSelectionForCount(lockedSelections, snapshotCount);
        screening = [];
        screeningArtifacts = struct();
    else
        screening = uav.experiment.screenClassicParameters(cfg, snapshotCount);
        selection = screening.selection;
        screeningArtifacts = saveScreening(screening, cfg, snapshotCount);
    end

    formalCfg = uav.experiment.applyClassicParameterSelection(cfg, selection);
    formalCfg.plot.visible = false;
    formalCfg.plot.closeAfterExport = true;
    formalCfg = configureScenarioOutput(formalCfg, snapshotCount);
    fprintf('[经典参数研究] 参数已锁定，开始运行正式实验6：profile=%s，L=%d。\n', ...
        cfg.profile, snapshotCount);
    formalResult = uav.experiment.runClassicJitterSweep(formalCfg);
    [comparisonTable, scenarioAssessment] = assessFormalResult(formalResult);

    selections(snapshotIndex) = selection;
    scenarios(snapshotIndex) = struct( ...
        'snapshotCount', snapshotCount, ...
        'screening', screening, ...
        'screeningArtifacts', screeningArtifacts, ...
        'selection', selection, ...
        'formalResult', formalResult, ...
        'minimumIncmMedianSinrDb', ...
            scenarioAssessment.minimumIncmMedianSinrDb, ...
        'incmTargetMet', scenarioAssessment.incmTargetMet, ...
        'incmDominatesPracticalMethodsAtEveryPoint', ...
            scenarioAssessment.incmDominatesPracticalMethodsAtEveryPoint);
    comparisonTables{snapshotIndex} = comparisonTable;
    fprintf(['[经典参数研究] profile=%s，L=%d完成；INCM最差抖动点' ...
        '中位SINR=%.3f dB，15 dB目标=%d，逐点领先实用基线=%d。\n'], ...
        cfg.profile, snapshotCount, ...
        scenarioAssessment.minimumIncmMedianSinrDb, ...
        scenarioAssessment.incmTargetMet, ...
        scenarioAssessment.incmDominatesPracticalMethodsAtEveryPoint);
end

comparisonTable = vertcat(comparisonTables{:});
study = struct( ...
    'profile', cfg.profile, ...
    'validationOnly', isValidationOnly, ...
    'scoreRule', cfg.experiments.classicTuning.scoreRule, ...
    'targetMinimumMedianSinrDb', ...
        cfg.experiments.classicTuning.targetMinimumMedianSinrDb, ...
    'methodNames', configuredMethods, ...
    'selections', selections, ...
    'scenarios', scenarios, ...
    'comparisonTable', comparisonTable);
study.artifacts = saveStudySummary(study, cfg);
end

function artifacts = saveScreening(screening, cfg, snapshotCount)
%SAVESCREENING 单独保存候选排名和完整筛选记录，防止只留下最优点。
directory = studyDirectory(cfg, snapshotCount);
ensureDirectory(directory);
baseName = sprintf('classic_parameter_screening_%s_L%d', ...
    char(cfg.profile), snapshotCount);
artifacts = struct( ...
    'mat', string(fullfile(directory, baseName + ".mat")), ...
    'csv', string(fullfile(directory, baseName + ".csv")));
save(artifacts.mat, 'screening', '-v7.3');
writetable(screening.ranking, artifacts.csv);
end

function cfg = configureScenarioOutput(cfg, snapshotCount)
%CONFIGURESCENARIOOUTPUT 为不同profile和快拍数建立互不覆盖的结果目录。
directory = studyDirectory(cfg, snapshotCount);
cfg.output.cacheDir = fullfile(directory, 'cache');
cfg.output.rawDir = fullfile(directory, 'raw');
cfg.output.figureDir = fullfile(directory, 'figures');
cfg.output.tableDir = fullfile(directory, 'tables');
cfg.output.logDir = fullfile(directory, 'logs');
cfg = uav.config.validate(cfg);
end

function directory = studyDirectory(cfg, snapshotCount)
%STUDYDIRECTORY 返回本次profile和快拍数专属目录。
directory = fullfile(cfg.output.rootDir, 'results', ...
    'classic_parameter_study', char(cfg.profile), sprintf('L%d', snapshotCount));
end

function [output, assessment] = assessFormalResult(result)
%ASSESSFORMALRESULT 检查INCM的15 dB目标和逐抖动点实际领先关系。
methodNames = reshape(result.methodNames, 1, []);
medianDb = result.summary.sinr.medianDb;
minimumPointMedianSinrDb = min(medianDb, [], 1);
overallMedianSinrDb = zeros(1, numel(methodNames));
for methodIndex = 1:numel(methodNames)
    values = result.raw.sinrLinear(:, :, :, methodIndex);
    overallMedianSinrDb(methodIndex) = 10 * log10(quantile(values(:), 0.5));
end
incmIndex = methodNames == "static_incm_mvdr";
otherPractical = methodNames ~= "oracle" & ...
    methodNames ~= "static_incm_mvdr";
incmDominanceByMethod = false(1, numel(methodNames));
for methodIndex = 1:numel(methodNames)
    incmDominanceByMethod(methodIndex) = all( ...
        medianDb(:, incmIndex) > medianDb(:, methodIndex));
end
incmDominanceByMethod(incmIndex) = true;
targetDb = result.cfg.experiments.classicTuning.targetMinimumMedianSinrDb;
assessment = struct( ...
    'minimumIncmMedianSinrDb', minimumPointMedianSinrDb(incmIndex), ...
    'incmTargetMet', minimumPointMedianSinrDb(incmIndex) >= targetDb, ...
    'incmDominatesPracticalMethodsAtEveryPoint', ...
        all(incmDominanceByMethod(otherPractical)));
snapshotColumn = repmat(result.cfg.timeline.L, numel(methodNames), 1);
output = table(snapshotColumn, methodNames(:), ...
    minimumPointMedianSinrDb(:), overallMedianSinrDb(:), ...
    (minimumPointMedianSinrDb(incmIndex) - ...
        minimumPointMedianSinrDb(:)), ...
    incmDominanceByMethod(:), ...
    repmat(assessment.incmTargetMet, numel(methodNames), 1), ...
    'VariableNames', {'snapshotCount', 'method', ...
        'minimumPointMedianSinrDb', 'overallMedianSinrDb', ...
        'incmMinimumMedianAdvantageDb', ...
        'incmHigherAtEveryJitterPoint', 'incmTargetMet'});
end

function artifacts = saveStudySummary(study, cfg)
%SAVESTUDYSUMMARY 保存轻量研究摘要；正式原始数组仍由实验6结果包保存。
directory = fullfile(cfg.output.rootDir, 'results', ...
    'classic_parameter_study', char(cfg.profile));
ensureDirectory(directory);
baseName = "classic_parameter_study_" + cfg.profile;
artifacts = struct( ...
    'mat', string(fullfile(directory, baseName + ".mat")), ...
    'csv', string(fullfile(directory, baseName + ".csv")));
% 避免在总摘要MAT中重复保存每个正式结果包的大型逐试次数组。
studyForSave = study;
for index = 1:numel(studyForSave.scenarios)
    formalResult = studyForSave.scenarios(index).formalResult;
    studyForSave.scenarios(index).formalResult = struct( ...
        'experimentName', formalResult.experimentName, ...
        'methodNames', formalResult.methodNames, ...
        'artifacts', formalResult.artifacts, ...
        'minimumMedianSinrDb', ...
            min(formalResult.summary.sinr.medianDb, [], 1));
end
save(artifacts.mat, 'studyForSave', '-v7.3');
writetable(study.comparisonTable, artifacts.csv);
end

function validateLockedSelections(selections, snapshotCounts)
%VALIDATELOCKEDSELECTIONS 要求每个快拍条件恰有一套smoke锁定参数。
if ~isstruct(selections) || numel(selections) ~= numel(snapshotCounts)
    error('uav:experiment:InvalidLockedClassicParameters', ...
        '锁定参数数量必须与classicTuning.snapshotCounts一致。');
end
counts = [selections.snapshotCount];
if numel(unique(counts)) ~= numel(counts) || ...
        ~isequal(sort(counts), sort(snapshotCounts))
    error('uav:experiment:InvalidLockedClassicParameters', ...
        '每个配置快拍数必须恰好对应一套锁定参数。');
end
end

function selection = lockedSelectionForCount(selections, snapshotCount)
%LOCKEDSELECTIONFORCOUNT 按快拍数读取锁定值，不依赖结构数组顺序。
index = find([selections.snapshotCount] == snapshotCount, 1);
selection = selections(index);
end

function selection = emptySelection()
%EMPTYSELECTION 预分配固定字段的锁定参数结构。
selection = struct( ...
    'snapshotCount', NaN, ...
    'dlDiagonalLoading', NaN, ...
    'espSignalSubspaceDimension', NaN, ...
    'wcoDesignJitterStdDeg', NaN, ...
    'staticSpectrumDiagonalLoading', NaN, ...
    'staticDesiredExclusionHalfWidthDeg', NaN, ...
    'staticIncmShrinkage', NaN);
end

function ensureDirectory(pathValue)
%ENSUREDIRECTORY 创建本研究专属目录，不删除或移动已有结果。
if ~isfolder(pathValue)
    mkdir(pathValue);
end
end
