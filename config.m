function cfg = config(profile)
%CONFIG 生成一套可复现的无人机姿态抖动仿真配置。
%   cfg = config(profile)
%
%   输入：
%     profile - 工作规模，可取 "smoke"、"preliminary" 或 "paper"。
%   输出：
%     cfg     - 已经通过 uav.config.validate 校验并补齐派生量的结构体。
%
%   设计约定：本文件是正式仿真的唯一数值参数入口。算法函数和实验入口
%   只读取 cfg，不应在其内部另设场景数值。角度在本文件中以度给出，经过
%   配置校验后，模型计算统一使用弧度或无量纲方向余弦。

arguments
    profile (1,1) string = "preliminary"
end

cfg.profile = lower(profile);
% 三个 profile 只改变计算工作量，不改变系统模型和算法定义。
% 各参数影响如下：
% - K：实验1和动态稳定性实验的时间长度。K=100 对应100 ms。
% - nTrials：独立蒙特卡洛试次，对置信区间可靠性影响最大。重复做多少次实验。
% - gridSize：二维Capon角域每个方向余弦轴的网格点数。51对应约51×51网格。
% - sweepPeriods：实验2、实验3和新增经典方法实验中，每个试次的周期数。即不一定把上面的 K 周期全部用完，而是只取前 sweepPeriods 周期作为扫描点。
% - ablationPeriods：消融实验每试次周期数。它和sweepPeriods的含义相同，只是专门供消融实验使用。
% - bootstrapReplicates：置信区间重采样次数，不增加新的物理仿真试次。对已有数据反复重采样，计算置信区间。形象地说，你已经拍了50段视频。现在从这50段里面“有放回地抽50段”，计算一次中位数；重复抽取500遍，用这些中位数估计置信区间。
switch cfg.profile
    case "smoke"
        workload = struct('K', 20, 'nTrials', 3, 'gridSize', 21, ...
            'sweepPeriods', 2, 'ablationPeriods', 2, ...
            'bootstrapReplicates', 100);
    case "preliminary"
        % workload = struct('K', 100, 'nTrials', 100, 'gridSize', 51, ...
        %     'sweepPeriods', 100, 'ablationPeriods', 100, ...
        %     'bootstrapReplicates', 1000);
        workload = struct('K', 100, 'nTrials', 30, 'gridSize', 51, ...
            'sweepPeriods', 20, 'ablationPeriods', 50, ...
            'bootstrapReplicates', 500);
    case "paper"
        workload = struct('K', 500, 'nTrials', 500, 'gridSize', 101, ...
            'sweepPeriods', 500, 'ablationPeriods', 500, ...
            'bootstrapReplicates', 2000);
    otherwise
        error('uav:config:UnknownProfile', ...
            'Profile must be "smoke", "preliminary", or "paper".');
end

% 随机流：所有试验从同一基种子出发，再由实验模块分配互不重叠的子流。
cfg.random = struct('baseSeed', 20260827, 'generator', "Threefry");

% 阵列：Nx、Ny 分别是 x/y 方向阵元数，间距用波长归一化。
% Nx>1且Ny=1时自动使用沿x轴的ULA；Nx、Ny均大于1时使用UPA。
% 本次不扩展沿y轴ULA或单阵元模式；不要用Nx=1触发本次的一维算法。
cfg.array = struct('Nx', 3, 'Ny', 3, 'spacingOverLambda', [0.5, 0.5], ...
    ... % ULA第一列为正侧向方位角：0度朝+y，正角向+x；忽略高度角。
    ... % UPA不使用此约定。该标记也用于区分旧MAT中的三维投影模型。
    'ulaDirectionConvention', "azimuth_broadside");

% 时间轴：dtSec 是处理周期，K 是总周期数，L 是每周期快拍数。
cfg.timeline = struct('dtSec', 1e-3, 'K', workload.K, 'L', 32);

% 姿态：[roll,pitch,yaw]；nominalDeg是标准姿态角向量，stdDeg 是稳态RMS，rho 是一阶过程相关系数。
cfg.attitude = struct( ...
    'nominalDeg', [0, 0, 0], ...
    'stdDeg', [5, 5, 5], ...
    'rho', [0.95, 0.95, 0.98]);

% UPA为世界坐标[方位角,高度角]；ULA只取第一列方位角[-90,90]度，
% 在水平面按[sin(方位角),cos(方位角),0]构造固定方向，第二列忽略。
% 零名义姿态下ULA入射角即第一列；之后仍按完整三轴姿态旋转。
cfg.sources = struct( ...
    'desiredAzElDeg', [0, -35], ...
    'interfererAzElDeg', [40, -25; -55, -20], ...
    'interfererInrDb', [30, 30]);

% 功率采用“接收机噪声功率为基准”的定义；训练序列使用独立QPSK符号。
% noisePower 表示“经过接收滤波后、在当前处理带宽内的总等效噪声功率”。不是噪声功率谱密度。因此不需要再乘带宽。
cfg.signal = struct('snrDb', 10, 'noisePower', 1, 'pilotModulation', "QPSK");

% Capon谱、谱对齐、峰值筛选和局部非均匀求积控制量。
% gridSize在UPA中为每个方向余弦轴的点数；ULA中为[-pi/2,pi/2]
% 上的等角中点数，积分权重为d(theta)，沿用研究分支的一维积分约定。
% ULA等效角theta=asin(u_x)，不是世界方位角。排除半宽仍使用下面的度数。
% 'desiredExclusionHalfWidthDeg', 7, ...
cfg.spectrum = struct( ...
    'gridSize', workload.gridSize, ...
    ... % ULA六种静态重构共用高密度候选网格；URGLQ另生成局部高斯节点。
    'ulaGridSize', 2001, ...
    'desiredExclusionHalfWidthDeg', 25, ...
    ... % UPA读取上方排除半宽；ULA单独用5度。当前ULA期望0度，干扰40/-55度。
    ... % 这是初始几何分区，不保证覆盖5度RMS姿态误差；动态适用性需另行扫描。
    'ulaDesiredExclusionHalfWidthDeg', 5, ...
    'diagonalLoading', 1e-2, ...
    'noiseEigenvalueFraction', 0.5, ...
    'alignmentMaxShiftBins', [2, 2], ...
    'alignmentMinCorrelation', 0.25, ...
    'alignmentAmbiguityMargin', 0.05, ...
    'alignmentMinimumOverlap', 9, ...
    'peakThresholdRatio', 0.15, ...
    'peakNmsRadiusBins', 1, ...
    'quadratureCoarseStride', 2, ...
    'quadratureFineRadiusBins', 1, ...
    'quadratureRefinement', 3, ...
    'quadratureDedupTolerance', 1e-12);

% INCM稀疏目标、结构修复以及消融开关。训练序列投影默认关闭。
% 'shrinkage', 0.05, ...
cfg.incm = struct( ...
    'shrinkage', 0, ...
    'eigenvalueFloorRatio', 1e-6, ...
    'noiseFloorRatio', 1e-6, ...
    'lambdaS', 0.05, ...
    'lambdaT', 0.10, ...
    ... % 旧字段保留兼容；validate会将其同步为下方localCovfit的共用参数。
    'staticCovfit', struct( ...
        'loadingRatio', 1e-3, ...
        'fitRegularization', 0, ...
        'peakThresholdRatio', 0.15, ...
        'peakNmsRadiusBins', 0, ...
        'maximumCandidateCount', 7), ...
    ... % 两种CovFit的唯一参数入口；radiusBins/solver只控制连续细化。
    ... % 以原细化版参数为基准，不校正最终期望导向。
    'localCovfit', struct( ...
        'loadingRatio',1e-3,'fitRegularization',0, ...
        'peakThresholdRatio',0.15,'peakNmsRadiusBins',0,'maximumCandidateCount',7, ...
        'radiusBins',2,'kktTolerance',1e-8, ...
        'solver',struct('maxIterations',500,'optimalityTolerance',1e-9, ...
        'constraintTolerance',1e-6,'stepTolerance',1e-12,'feasibilityTolerance',1e-8)), ...
    'ablation', struct( ...
        'temporalContinuity', true, ...
        'alignment', true, ...
        'adaptiveQuadrature', true, ...
        'structureEnhancement', true, ...
        'pilotProjection', false));

% 两种新增对照共用观测驱动的局部峰候选；不使用真实方向或真实干扰数。
% 与CovFit默认前端一致，但独立配置，不隐式跟随其它方法调参。
cfg.incm.caponCandidates=struct('loadingRatio',1e-3, ...
    'peakThresholdRatio',0.15,'peakNmsRadiusBins',0,'maximumCandidateCount',7);
% 峰点功率直接读取未加载Capon值，不乘求积面积、不扣谱底，再加估计噪声I。
% powerLoadingRatio>0是显式加载扩展；默认0时秩亏SCM标记不适用，不伪逆。
cfg.incm.caponPoint=struct('powerLoadingRatio',0);
% URGLQ仅保留局部积分与高斯求积，不做期望投影或期望导向校正。
% ULA为论文的一维局部区间；UPA为用户确认的方位/高度矩形立体角扩展。
cfg.incm.urglq=struct('powerLoadingRatio',0,'quadratureOrder',3, ...
    'ulaHalfWidthDeg',8,'upaAzElHalfWidthDeg',[8,8], ...
    'upaMeasure',"solid_angle");

% 三类权值求解器的共用配置：
% 1. 普通MVDR；
% 2. 对角加载MVDR；
% 3. 静态/时序INCM方法共用的球形失配鲁棒权值。
% 波束形成：epsilonS 会在正式实验开始前通过固定设计分布重新标定；
% gamma 是鲁棒目标中的范数正则项。epsilonS=0 时必须严格退化为MVDR。
cfg.beamforming = struct( ...
    'diagonalLoading', 1e-2, ...
    'epsilonS', 0, ...
    'gamma', 1e-3, ...
    'covariancePsdTolerance', 1e-10, ...
    'minimumReciprocalCondition', 1e-8, ...
    'classic', struct( ...
        'nlms', struct('stepSize', 0.2, 'regularization', 1e-3), ...
        'rls', struct('forgettingFactor', 0.995, 'initialInverseScale', 100), ...
        'pi', struct('referenceElement', 1), ...
        'esp', struct('signalSubspaceDimension', 3)), ...
    'solver', struct( ...
        'optimalityTolerance', 1e-9, ...
        'constraintTolerance', 1e-9, ...
        'stepTolerance', 1e-12, ...
        'initialInteriorMargin', 1e-6, ...
        'feasibilityTolerance', 1e-8, ...
        'maxIterations', 500), ...
    'calibration', struct( ...
        ... % ULA固定球形半径epsilon=sqrt(scale*M)，不按试次真值或SINR调参。
        ... % 用户授权指定；沿用研究分支的0.3比例，UPA不使用这个字段。
        'ulaSquaredRadiusScale', 0.3, ...
        'designJitterStdDeg', [4, 4, 4], ...
        'quantile', 0.95, ...
        'sampleCount', 2000, ...
        'substream', 401));

% 配对蒙特卡洛试验次数。
cfg.monteCarlo = struct('nTrials', workload.nTrials);

% 各实验的扫描点、统计规则和确定性子流编号规划。
% 'jitterSweepDeg', [0, 0.5, 1, 2, 4, 8], ...
% 'exp02MethodNames', ["oracle", "frozen", "scm", "dl", "incm_integral_processed", "temporal"], ...
% 'classicJitterMethodNames', ["oracle", "nsb", "frozen_mvdr", ...
%     "scm_mvdr", "nlms", "rls", "pi", "dl_mvdr", "esp", "wco", ...
%     "incm_covfit", "incm_covfit_refined"], ...
% 'classicJitterMethodNames', ["oracle", "dl_mvdr", "esp", "wco", "incm_covfit", "incm_covfit_refined"], ...
cfg.experiments = struct( ...
    'jitterSweepDeg', (0:1:20), ...
    'snapshotSweep', (32:32:1024), ...
    'snrSweepDb', (-10:5:30), ...
    'classicSnrSnapshotCount', 32, ...
    ... % 实验8固定各轴RMS为5度；不表示三轴合成RMS或每周期角度固定5度。
    'classicSnrJitterStdDeg', [5, 5, 5], ...
    'methodNames', ["oracle", "frozen", "scm", "dl", "incm_integral_processed", "temporal"], ...
    'exp02MethodNames', ["oracle"], ...
    ... % 方法组合可选；六种静态重构均使用incm_*新标识，历史名称仍可输入。
    ... % 可额外选择"incm_integral_origin"：不加载、不扣底、不显式加噪声的原式Rec。
    'classicJitterMethodNames', ["oracle", "dl_mvdr", "esp", "wco", "incm_integral_origin", "incm_capon_point", ...
    "incm_covfit", "incm_covfit_refined"], ...
    ... % 快拍扫描固定使用cfg.attitude.stdDeg，不扫描姿态RMS。
    'classicSnapshotMethodNames', ["oracle", "dl_mvdr", "esp", "wco", "incm_integral_origin", "incm_capon_point", ...
    "incm_covfit", "incm_covfit_refined"], ...
    ... % 实验8单独选择方法，不与实验6/7的方法列表联动。
    'classicSnrMethodNames', ["oracle", "dl_mvdr", "esp", "wco", "incm_integral_origin", "incm_capon_point", ...
    "incm_covfit", "incm_covfit_refined"], ...
    'classicTuning', struct( ...
        ... % 两种快拍条件分别筛选，但每种方法都在相同观测上独立取最优参数。
        'snapshotCounts', [8, 64], ...
        ... % 评分取各抖动点SINR中位数中的最小值，优先保证整条曲线稳定。
        'scoreRule', "minimum-point-median", ...
        'targetMinimumMedianSinrDb', 15, ...
        ... % DL-MVDR显式加载系数，实际加载量还会乘SCM平均功率。
        'dlLoadingCandidates', [1e-3, 1e-2, 1e-1, 1], ...
        ... % ESP保留的主特征子空间维数。
        'espDimensionCandidates', [2, 3, 4, 5], ...
        ... % WCO离线半径标定所用的三轴等RMS设计抖动（单位：度）。
        'wcoDesignJitterStdDegCandidates', [2, 4, 6, 8], ...
        ... % 静态INCM采用逐字段坐标筛选，避免全部笛卡尔积造成无谓计算。
        'staticSpectrumLoadingCandidates', [1e-3, 1e-2, 1e-1], ...
        ... % 扫描上限25°用于覆盖三轴8°RMS时的较大合成方向失配；
        ... % 不再继续增大，以免排除区侵入示例邻区干扰方向。
        'staticExclusionHalfWidthDegCandidates', [5, 7, 10, 12, 15, 20, 25], ...
        'staticShrinkageCandidates', [0, 0.05, 0.1, 0.2]), ...
    'ablationNames', ["full", "lambda_t_zero", "identity_alignment", ...
        "uniform_quadrature", "no_structure", "pilot_projection"], ...
    'periodCounts', struct( ...
        'modelValidation', workload.K, ...
        'jitterSweep', workload.sweepPeriods, ...
        'snapshotSweep', workload.sweepPeriods, ...
        'snrSweep', workload.sweepPeriods, ...
        'dynamicStability', workload.K, ...
        'ablation', workload.ablationPeriods), ...
    'bootstrapReplicates', workload.bootstrapReplicates, ...
    'outageThresholdDb', -5, ...
    'oracleTolerance', 1e-9, ...
    'aggregation', struct( ...
        'medianQuantile', 0.5, ...
        'lowQuantile', 0.05, ...
        'confidenceQuantiles', [0.025, 0.975], ...
        'runtimeQuantile', 0.95), ...
    'substreams', struct( ...
        'experimentStride', 1000000000, ...
        'pointStride', 2000000, ...
        'trialStride', 2000, ...
        'scenarioOffset', 1, ...
        'snapshotOffset', 100, ...
        'bootstrapOffset', 800), ...
    'codeVersion', "uav-initial-simulator-task5-v1");

% 绘图采用统一尺寸和样式；单实验默认显示并保留，run_all批处理导出后关闭。
cfg.plot = struct( ...
    'visible', true, ...
    'closeAfterExport', false, ...
    'saveFigures', true, ...
    'formats', ["fig", "pdf", "png"], ...
    'resolutionDpi', 180, ...
    'figurePosition', [100, 100, 1000, 700], ...
    'lineWidth', 2.4, ...
    'markerSize', 10, ...
    'fontSize', 25, ...
    'maxTraceTrials', 3);

% overwrite=true 允许同一profile的结果被新一轮完整实验替换。
cfg.output = struct('overwrite', true);

% 校验原始配置并计算M、J、功率、名义流形和二维网格流形等派生量。
cfg = uav.config.validate(cfg);
end
