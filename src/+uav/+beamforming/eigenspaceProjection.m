function [w, diagnostics] = eigenspaceProjection(R, aRef, cfg)
%EIGENSPACEPROJECTION 实现经典特征子空间投影波束形成。
%   对SCM作特征分解，取配置数量的最大特征值对应向量构成信号子空间，
%   将标称期望导向矢量投影至该子空间，再用投影矢量求标准MVDR权值。

M = cfg.derived.M;
if ~isequal(size(R), [M, M]) || any(~isfinite(R), 'all') || ...
        ~isvector(aRef) || numel(aRef) ~= M || any(~isfinite(aRef))
    error('uav:beamforming:InvalidEigenspaceInput', ...
        'ESP requires a finite M-by-M covariance and matching reference vector.');
end
R = (R + R') / 2;
[eigenvectors, eigenvalueMatrix] = eig(R, 'vector');
[eigenvalues, order] = sort(real(eigenvalueMatrix), 'descend');
configuredDimension = cfg.beamforming.classic.esp.signalSubspaceDimension;
% 配置给出的是期望保留的最大子空间维数。为兼容任意矩形小阵列，
% 实际维数不能超过当前阵元数；这不会使用真实信号源数量。
dimension = min(configuredDimension, M);
signalSubspace = eigenvectors(:, order(1:dimension));
projectedReference = signalSubspace * (signalSubspace' * aRef(:));
if norm(projectedReference) <= eps(max(1, norm(aRef)))
    error('uav:beamforming:DegenerateProjection', ...
        'The nominal reference has negligible projection in the signal subspace.');
end
[w, mvdrDiagnostics] = uav.beamforming.solve("mvdr", R, ...
    projectedReference, cfg);
diagnostics = struct('method', "esp", ...
    'configuredSignalSubspaceDimension', configuredDimension, ...
    'signalSubspaceDimension', dimension, ...
    'signalSubspace', signalSubspace, ...
    'eigenvaluesDescending', eigenvalues, ...
    'projectedReference', projectedReference, ...
    'projectionResidual', norm(aRef(:) - projectedReference), ...
    'mvdr', mvdrDiagnostics);
end
