function [raw, seeds] = collectMethods( ...
        cfg, experimentIndex, pointIndex, periodCount, methodNames)
%COLLECTMETHODS 生成配对观测并收集所选方法的原始指标。
%   方法性能字段尺寸为[试次×周期×方法]；与方法无关的期望导向失配
%   尺寸为[试次×周期]；snapshotSignatures额外有长度4的摘要维。
%   seeds保存实际使用的场景和快拍子流，支持独立重建复核。“配对”表示
%   同一试次、同一周期的全部所选方法只生成一次obs。

if nargin < 5
    % 保留原四参数接口，其他实验继续使用固定六方法组合。
    methodNames = cfg.experiments.methodNames;
end
methodNames = reshape(string(methodNames), 1, []);
trialCount = cfg.monteCarlo.nTrials;
methodCount = numel(methodNames);
% 不可用的INCM指标用NaN表示，Oracle/SCM/DL不伪造估计误差。
raw = struct( ...
    'sinrLinear', zeros(trialCount, periodCount, methodCount), ...
    'desiredGain', zeros(trialCount, periodCount, methodCount), ...
    'interferenceLeakage', zeros(trialCount, periodCount, methodCount), ...
    'runtimeSec', zeros(trialCount, periodCount, methodCount), ...
    'incmNmse', nan(trialCount, periodCount, methodCount), ...
    'incmMinimumEigenvalue', nan(trialCount, periodCount, methodCount), ...
    'incmConditionNumber', nan(trialCount, periodCount, methodCount), ...
    'desiredSteeringMismatchNormalized', zeros(trialCount, periodCount), ...
    'snapshotSignatures', zeros(trialCount, periodCount, methodCount, 4));
seeds = struct( ...
    'scenarioSubstreams', zeros(trialCount, 1), ...
    'snapshotSubstreams', zeros(trialCount, periodCount));
for trialIndex = 1:trialCount
    % 每个试次只生成一条完整姿态轨迹，各周期在该轨迹上取对应状态。
    scenarioSubstream = uav.experiment.substream(cfg, experimentIndex, ...
        pointIndex, trialIndex, 0, "scenario");
    seeds.scenarioSubstreams(trialIndex) = scenarioSubstream;
    scenario = uav.scenario.generate(cfg, ...
        uav.util.makeStream(cfg.random.baseSeed, scenarioSubstream));
    runnerState = [];
    for periodIndex = 1:periodCount
        % 快拍子流按周期隔离，方法之间不重新抽取信号或噪声。
        snapshotSubstream = uav.experiment.substream(cfg, experimentIndex, ...
            pointIndex, trialIndex, periodIndex, "snapshot");
        seeds.snapshotSubstreams(trialIndex, periodIndex) = snapshotSubstream;
        obs = uav.scenario.generatePeriod(cfg, scenario, periodIndex, ...
            uav.util.makeStream(cfg.random.baseSeed, snapshotSubstream));
        % 该真值仅用于实验评价，不进入任何非Oracle算法输入。
        desiredActual = obs.truth.trueASVs(:, 1);
        desiredNominal = cfg.derived.nominalSteeringReference;
        raw.desiredSteeringMismatchNormalized(trialIndex, periodIndex) = ...
            norm(desiredActual - desiredNominal, 2) / norm(desiredNominal, 2);
        [record, runnerState] = uav.experiment.runMethods( ...
            obs, runnerState, cfg, methodNames);
        raw.sinrLinear(trialIndex, periodIndex, :) = record.sinrLinear;
        raw.desiredGain(trialIndex, periodIndex, :) = record.desiredGain;
        raw.interferenceLeakage(trialIndex, periodIndex, :) = ...
            record.interferenceLeakage;
        raw.runtimeSec(trialIndex, periodIndex, :) = record.runtimeSec;
        raw.incmNmse(trialIndex, periodIndex, :) = record.incmNmse;
        raw.incmMinimumEigenvalue(trialIndex, periodIndex, :) = ...
            record.incmMinimumEigenvalue;
        raw.incmConditionNumber(trialIndex, periodIndex, :) = ...
            record.incmConditionNumber;
        raw.snapshotSignatures(trialIndex, periodIndex, :, :) = ...
            reshape(record.snapshotSignatures, 1, 1, methodCount, 4);
        oracleIndex = find(methodNames == "oracle", 1);
        if ~isempty(oracleIndex)
            otherIndices = setdiff(1:methodCount, oracleIndex);
            if ~isempty(otherIndices) && ...
                    record.sinrLinear(oracleIndex) + ...
                    cfg.experiments.oracleTolerance < ...
                    max(record.sinrLinear(otherIndices))
                % 相同真实INCM下，Oracle MVDR理论上不应劣于非Oracle权值。
                error('uav:experiment:OracleBoundViolation', ...
                    'Oracle SINR fell below a non-Oracle weight on the same truth.');
            end
        end
    end
end
end
