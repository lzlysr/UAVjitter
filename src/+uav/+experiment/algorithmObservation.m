function safe = algorithmObservation(obs)
%ALGORITHMOBSERVATION Return the whitelist observation passed to non-Oracle code.

required = {'X', 'Rx', 'pilot', 'k', 'nominalSteeringReference', 'truth'};
if ~isstruct(obs) || ~all(isfield(obs, required))
    error('uav:experiment:InvalidObservation', ...
        'Generated observations must provide algorithm fields and isolated truth.');
end
safe = struct( ...
    'X', obs.X, ...
    'Rx', obs.Rx, ...
    'pilot', obs.pilot, ...
    'k', obs.k, ...
    'nominalSteeringReference', obs.nominalSteeringReference);
if isfield(safe, 'truth')
    error('uav:experiment:TruthIsolationFailure', ...
        'Non-Oracle observation views must not contain truth.');
end
end
