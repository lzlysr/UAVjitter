function record = runUpaDiagnosisMethods(obs, cfg, methodNames, integrationGrid)
%RUNUPADIAGNOSISMETHODS 在相同UPA观测上执行实验9的五种诊断方法。
%   非Oracle方法先经algorithmObservation白名单剥离真值；Oracle求权值
%   与各方法权值完成后的统一指标评价才读取obs.truth。原始Rec只使用
%   integrationGrid.includedMask对应的流形列和求积权重。

methodNames = reshape(string(methodNames), 1, []);
validateInputs(obs, cfg, methodNames, integrationGrid);
M = size(obs.Rx, 1);
methodCfg = diagnosisMethodConfiguration(cfg, M);
methodCount = numel(methodNames);
sinrLinear = nan(1, methodCount);
desiredGain = nan(1, methodCount);
interferenceLeakage = nan(1, methodCount);
runtimeSec = nan(1, methodCount);
incmNmse = nan(1, methodCount);
weights = complex(nan(M, methodCount));
diagnostics = cell(1, methodCount);
status = repmat("ok", 1, methodCount);
reason = repmat("", 1, methodCount);
reasonCode = repmat("", 1, methodCount);

% 所有非Oracle方法只构造一次白名单视图，确保它们收到完全相同的观测。
hasNonOracle = any(methodNames ~= "oracle");
if hasNonOracle
    safeObservation = uav.experiment.algorithmObservation(obs);
else
    safeObservation = struct();
end
snapshotCount = size(obs.X, 2);
% 名义参考随观测携带，五种方法在本调用中共享同一个参考向量。
aRef = obs.nominalSteeringReference;

for methodIndex = 1:methodCount
    methodTimer = tic;
    method = methodNames(methodIndex);
    estimatedIncm = [];
    methodDiagnostics = struct();
    switch method
        case "oracle"
            [weight, beamformingDiagnostics] = uav.beamforming.solve( ...
                "mvdr", obs.truth.trueIncm, obs.truth.trueASVs(:, 1), methodCfg);
            methodDiagnostics = struct( ...
                'truthAccess', "oracle-only", ...
                'usedTruth', true, ...
                'beamforming', beamformingDiagnostics);
        case "esp"
            [weight, beamformingDiagnostics] = uav.beamforming.eigenspaceProjection( ...
                safeObservation.Rx, aRef, methodCfg);
            methodDiagnostics = nonOracleDiagnostics(beamformingDiagnostics);
        case "wco"
            [weight, beamformingDiagnostics] = uav.beamforming.solve( ...
                "wco", safeObservation.Rx, aRef, methodCfg);
            methodDiagnostics = nonOracleDiagnostics(beamformingDiagnostics);
            methodDiagnostics.paperSquaredRadius = ...
                cfg.literature.guLeshem2012.wcoSquaredRadiusScale * M;
        case "gu_leshem2012_rec"
            if snapshotCount < M
                % L<M时SCM必然奇异；必须保持原始Rec不适用且绝不调用核心。
                runtimeSec(methodIndex) = toc(methodTimer);
                status(methodIndex) = "singular-not-applicable";
                reason(methodIndex) = "快拍数L小于阵元数M，原始Rec样本协方差奇异。";
                reasonCode(methodIndex) = "L-less-than-M";
                diagnostics{methodIndex} = struct( ...
                    'algorithmInputHasTruth', false, ...
                    'usedTruth', false, ...
                    'coreInvoked', false, ...
                    'reasonChinese', "快拍数L小于阵元数M，未调用原始Rec核心函数。");
                continue;
            end
            included = integrationGrid.includedMask;
            [estimatedIncm, reconstructionDiagnostics] = uav.incm.guLeshem2012Rec( ...
                safeObservation.Rx, integrationGrid.manifold(:, included), ...
                integrationGrid.weights(included));
            [weight, beamformingDiagnostics] = uav.beamforming.solve( ...
                "mvdr", estimatedIncm, aRef, methodCfg);
            methodDiagnostics = nonOracleDiagnostics(beamformingDiagnostics);
            methodDiagnostics.reconstruction = reconstructionDiagnostics;
            % 估计矩阵仅供实验后与真值对比，不回流到任何候选或参数选择。
            methodDiagnostics.estimatedIncm = estimatedIncm;
            methodDiagnostics.coreInvoked = true;
        case "upa_covfit_incm"
            [estimatedIncm, reconstructionDiagnostics] = uav.incm.upaCovfit( ...
                safeObservation, methodCfg);
            [weight, beamformingDiagnostics] = uav.beamforming.solve( ...
                "mvdr", estimatedIncm, aRef, methodCfg);
            methodDiagnostics = nonOracleDiagnostics(beamformingDiagnostics);
            methodDiagnostics.reconstruction = reconstructionDiagnostics;
            % 估计矩阵仅供实验后与真值对比，不回流到任何候选或参数选择。
            methodDiagnostics.estimatedIncm = estimatedIncm;
            methodDiagnostics.usedTruth = reconstructionDiagnostics.usedTruth;
    end
    runtimeSec(methodIndex) = toc(methodTimer);
    metricTruth = obs.truth;
    if ~isempty(estimatedIncm)
        metricTruth.estimatedIncm = estimatedIncm;
    end
    metrics = uav.metrics.evaluate(weight, metricTruth, methodCfg);
    sinrLinear(methodIndex) = metrics.sinrLinear;
    desiredGain(methodIndex) = metrics.desiredGain;
    interferenceLeakage(methodIndex) = metrics.interferenceLeakage;
    if isfield(metrics, 'incmNmse')
        incmNmse(methodIndex) = metrics.incmNmse;
    end
    weights(:, methodIndex) = weight;
    diagnostics{methodIndex} = methodDiagnostics;
end

signature = uav.util.snapshotSignature(obs.X);
snapshotSignature = repmat(signature, methodCount, 1);
record = struct( ...
    'methodNames', methodNames, ...
    'sinrLinear', sinrLinear, ...
    'desiredGain', desiredGain, ...
    'interferenceLeakage', interferenceLeakage, ...
    'runtimeSec', runtimeSec, ...
    'incmNmse', incmNmse, ...
    'weights', weights, ...
    'diagnostics', {diagnostics}, ...
    'status', status, ...
    'reason', reason, ...
    'reasonCode', reasonCode, ...
    'snapshotSignature', snapshotSignature, ...
    'snapshotSignatures', snapshotSignature);
end

function methodCfg = diagnosisMethodConfiguration(cfg, M)
%DIAGNOSISMETHODCONFIGURATION 复用论文复现的ESP和WCO参数语义。
methodCfg = cfg;
paper = cfg.literature.guLeshem2012;
methodCfg.derived.M = M;
methodCfg.beamforming.classic.esp.signalSubspaceDimension = ...
    paper.espSignalSubspaceDimension;
methodCfg.beamforming.epsilonS = sqrt(paper.wcoSquaredRadiusScale * M);
end

function diagnostics = nonOracleDiagnostics(beamformingDiagnostics)
%NONORACLEDIAGNOSTICS 留存白名单审计字段，供测试和实验导出检查。
diagnostics = struct( ...
    'algorithmInputHasTruth', false, ...
    'usedTruth', false, ...
    'beamforming', beamformingDiagnostics);
end

function validateInputs(obs, cfg, methodNames, integrationGrid)
%VALIDATEINPUTS 校验完整评价观测、固定方法集合和Rec积分网格。
allowed = ["oracle", "esp", "wco", "gu_leshem2012_rec", "upa_covfit_incm"];
if isempty(methodNames) || any(strlength(methodNames) == 0) || ...
        numel(unique(methodNames)) ~= numel(methodNames) || ...
        any(~ismember(methodNames, allowed))
    error('uav:experiment:InvalidUpaDiagnosisMethodSelection', ...
        'UPA diagnosis methods must be a nonempty unique allowed subset.');
end
requiredObservation = {'X', 'Rx', 'pilot', 'k', ...
    'nominalSteeringReference', 'truth'};
if ~isstruct(obs) || ~all(isfield(obs, requiredObservation)) || ...
        ~isstruct(obs.truth)
    error('uav:experiment:InvalidUpaDiagnosisObservation', ...
        'UPA diagnosis requires a complete generated observation.');
end
if ~isstruct(cfg) || ~isfield(cfg, 'derived') || ...
        ~isfield(cfg.derived, 'M') || ...
        ~isfield(cfg.derived, 'nominalSteeringReference') || ...
        ~isfield(cfg, 'literature') || ...
        ~isfield(cfg.literature, 'guLeshem2012')
    error('uav:experiment:MissingUpaDiagnosisConfiguration', ...
        'A validated UPA diagnosis configuration is required.');
end
M = cfg.derived.M;
if size(obs.X, 1) ~= M || ~isequal(size(obs.Rx), [M, M]) || ...
        ~isvector(obs.nominalSteeringReference) || ...
        numel(obs.nominalSteeringReference) ~= M || ...
        any(~isfinite(obs.X), 'all') || any(~isfinite(obs.Rx), 'all') || ...
        any(~isfinite(obs.nominalSteeringReference))
    error('uav:experiment:InvalidUpaDiagnosisObservation', ...
        'Observation snapshots and covariance must match the configured array.');
end
requiredGrid = {'manifold', 'weights', 'includedMask'};
if ~isstruct(integrationGrid) || ~all(isfield(integrationGrid, requiredGrid)) || ...
        size(integrationGrid.manifold, 1) ~= M || ...
        size(integrationGrid.manifold, 2) ~= numel(integrationGrid.weights) || ...
        numel(integrationGrid.includedMask) ~= numel(integrationGrid.weights) || ...
        any(~isfinite(integrationGrid.manifold), 'all') || ...
        any(~isfinite(integrationGrid.weights)) || ...
        any(integrationGrid.weights < 0) || ...
        ~islogical(integrationGrid.includedMask)
    error('uav:experiment:InvalidUpaDiagnosisIntegrationGrid', ...
        'integrationGrid must provide a finite compatible manifold and weights.');
end
if any(methodNames == "gu_leshem2012_rec") && ...
        ~any(integrationGrid.includedMask)
    error('uav:experiment:InvalidUpaDiagnosisIntegrationGrid', ...
        'The original Rec requires at least one included integration point.');
end
end
