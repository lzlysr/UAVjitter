function screening = screenClassicParameters(cfg, snapshotCount)
%SCREENCLASSICPARAMETERS 公平筛选四种经典鲁棒方法的配置参数。
%   screening = screenClassicParameters(cfg, snapshotCount)
%
%   对DL-MVDR、ESP和WCO分别在config.m给出的候选集合中独立取最优值；
%   对静态Capon-INCM按“谱加载->期望区半宽->收缩系数”执行确定性的坐标
%   筛选。每个候选都复用实验6的同一组子流，因此不同参数看到完全相同的
%   姿态轨迹和阵列快拍。评分为各抖动点输出SINR中位数中的最小值。
%
%   本函数不绘图、不发布正式结果。选出的参数仍需传给
%   runClassicJitterSweep，在完整方法组合下生成最终图表和结果包。

if ~isnumeric(snapshotCount) || ~isscalar(snapshotCount) || ...
        ~isfinite(snapshotCount) || snapshotCount <= 0 || ...
        snapshotCount ~= floor(snapshotCount)
    error('uav:experiment:InvalidClassicTuningInput', ...
        '每周期快拍数必须是正整数。');
end
cfg = uav.config.validate(cfg);
tuning = cfg.experiments.classicTuning;
if ~ismember(snapshotCount, tuning.snapshotCounts)
    error('uav:experiment:InvalidClassicTuningInput', ...
        '快拍数必须来自classicTuning.snapshotCounts。');
end

selection = initialSelection(cfg, snapshotCount);
records = repmat(emptyRecord(), 0, 1);
selectedIndices = zeros(1, 4);

% 三种单参数方法分别独立选择自身的最大最差点中位SINR。
[records, selectedIndices(1), selection] = screenOneStage( ...
    records, cfg, selection, "dl_mvdr", "dl_loading", ...
    "dlDiagonalLoading", tuning.dlLoadingCandidates);
[records, selectedIndices(2), selection] = screenOneStage( ...
    records, cfg, selection, "esp", "subspace_dimension", ...
    "espSignalSubspaceDimension", tuning.espDimensionCandidates);
[records, selectedIndices(3), selection] = screenOneStage( ...
    records, cfg, selection, "wco", "design_jitter_rms_deg", ...
    "wcoDesignJitterStdDeg", tuning.wcoDesignJitterStdDegCandidates);

% 静态INCM含三个可调字段，采用预先固定顺序的坐标筛选，避免事后改变
% 搜索路径或穷举大量组合。最终阶段的胜出记录代表完整锁定配置。
[records, ~, selection] = screenOneStage( ...
    records, cfg, selection, "CovFit", ...
    "spectrum_loading", "staticSpectrumDiagonalLoading", ...
    tuning.staticSpectrumLoadingCandidates);
[records, ~, selection] = screenOneStage( ...
    records, cfg, selection, "CovFit", ...
    "exclusion_half_width_deg", ...
    "staticDesiredExclusionHalfWidthDeg", ...
    tuning.staticExclusionHalfWidthDegCandidates);
[records, selectedIndices(4), selection] = screenOneStage( ...
    records, cfg, selection, "CovFit", ...
    "incm_shrinkage", "staticIncmShrinkage", ...
    tuning.staticShrinkageCandidates);

ranking = recordsToTable(records);
ranking.selectedForStage(:) = false;
for index = 1:numel(records)
    ranking.selectedForStage(index) = records(index).selectedForStage;
end
selectedMethodSummary = ranking(selectedIndices, :);
selectedMethodSummary.Properties.RowNames = {};

screening = struct( ...
    'profile', cfg.profile, ...
    'snapshotCount', snapshotCount, ...
    'scoreRule', tuning.scoreRule, ...
    'targetMinimumMedianSinrDb', tuning.targetMinimumMedianSinrDb, ...
    'selection', selection, ...
    'ranking', ranking, ...
    'selectedMethodSummary', selectedMethodSummary, ...
    'records', records, ...
    'fairness', struct( ...
        'sharedObservationSubstreams', true, ...
        'experimentIndex', 6, ...
        'eachMethodOptimizedIndependently', true, ...
        'preliminaryRetuningAllowed', false));
end

function selection = initialSelection(cfg, snapshotCount)
%INITIALSELECTION 从当前配置提取坐标筛选的起点。
selection = struct( ...
    'snapshotCount', snapshotCount, ...
    'dlDiagonalLoading', cfg.beamforming.diagonalLoading, ...
    'espSignalSubspaceDimension', ...
        cfg.beamforming.classic.esp.signalSubspaceDimension, ...
    'wcoDesignJitterStdDeg', ...
        cfg.beamforming.calibration.designJitterStdDeg(1), ...
    'staticSpectrumDiagonalLoading', cfg.spectrum.diagonalLoading, ...
    'staticDesiredExclusionHalfWidthDeg', ...
        cfg.spectrum.desiredExclusionHalfWidthDeg, ...
    'staticIncmShrinkage', cfg.incm.shrinkage);
end

function [records, bestIndex, selection] = screenOneStage( ...
        records, baseCfg, selection, method, stage, fieldName, candidates)
%SCREENONESTAGE 在固定其余字段时筛选一个参数，并更新当前锁定值。
stageIndices = zeros(1, numel(candidates));
for candidateIndex = 1:numel(candidates)
    candidateSelection = selection;
    candidateSelection.(fieldName) = candidates(candidateIndex);
    try
        record = evaluateCandidate(baseCfg, candidateSelection, method, ...
            stage, fieldName, candidates(candidateIndex));
    catch exception
        if exception.identifier ~= "uav:beamforming:InfeasibleCalibration"
            rethrow(exception);
        end
        % 设计抖动过大时，95%导向误差半径可能达到||aRef||，此时WCO
        % 约束不存在可行解。该候选属于物理不可行，不应中断其余筛选。
        record = emptyRecord();
        record.method = method;
        record.stage = stage;
        record.parameterName = fieldName;
        record.parameterValue = candidates(candidateIndex);
        record.errorIdentifier = string(exception.identifier);
        record.errorMessage = string(exception.message);
    end
    records(end + 1, 1) = record; %#ok<AGROW>
    stageIndices(candidateIndex) = numel(records);
    if record.validCandidate
        fprintf(['[经典参数筛选] L=%d，方法=%s，阶段=%s，候选=%g，' ...
            '最差抖动点中位SINR=%.3f dB。\n'], ...
            selection.snapshotCount, method, stage, candidates(candidateIndex), ...
            record.minimumPointMedianSinrDb);
    else
        fprintf(['[经典参数筛选] L=%d，方法=%s，阶段=%s，候选=%g不可行，' ...
            '已记录并继续。\n'], selection.snapshotCount, method, stage, ...
            candidates(candidateIndex));
    end
end
bestIndex = chooseBest(records, stageIndices);
records(bestIndex).selectedForStage = true;
selection.(fieldName) = records(bestIndex).parameterValue;
fprintf('[经典参数筛选] L=%d，方法=%s，阶段=%s，锁定候选=%g。\n', ...
    selection.snapshotCount, method, stage, records(bestIndex).parameterValue);
end

function bestIndex = chooseBest(records, candidateIndices)
%CHOOSEBEST 先最大化最差点中位数，再以总体中位数确定并列名次。
candidateIndices = candidateIndices([records(candidateIndices).validCandidate]);
if isempty(candidateIndices)
    error('uav:experiment:NoFeasibleClassicCandidate', ...
        '当前筛选阶段没有任何可行候选参数。');
end
minimumScores = [records(candidateIndices).minimumPointMedianSinrDb];
bestMinimum = max(minimumScores);
ties = candidateIndices(minimumScores == bestMinimum);
overallScores = [records(ties).overallMedianSinrDb];
[~, localIndex] = max(overallScores);
bestIndex = ties(localIndex);
end

function record = evaluateCandidate(baseCfg, selection, method, stage, ...
        parameterName, parameterValue)
%EVALUATECANDIDATE 在所有抖动点上评价单个方法和单个参数候选。
timerValue = tic;
cfg = uav.experiment.applyClassicParameterSelection(baseCfg, selection);
[cfg, calibration] = uav.experiment.prepare(cfg);
jitterPoints = cfg.experiments.jitterSweepDeg;
trialCount = cfg.monteCarlo.nTrials;
periodCount = cfg.experiments.periodCounts.jitterSweep;
sinrLinear = zeros(trialCount, periodCount, numel(jitterPoints));
for pointIndex = 1:numel(jitterPoints)
    pointCfg = cfg;
    pointCfg.attitude.stdDeg = jitterPoints(pointIndex) * ones(1, 3);
    pointCfg = uav.config.validate(pointCfg);
    % validate会重建配置，显式恢复实验开始前固定标定的WCO半径。
    pointCfg.beamforming.epsilonS = cfg.beamforming.epsilonS;
    pointRaw = uav.experiment.collectClassicMethods(pointCfg, 6, ...
        pointIndex, periodCount, method);
    sinrLinear(:, :, pointIndex) = pointRaw.sinrLinear;
end

pointMedianLinear = zeros(numel(jitterPoints), 1);
for pointIndex = 1:numel(jitterPoints)
    pointValues = reshape(sinrLinear(:, :, pointIndex), [], 1);
    pointMedianLinear(pointIndex) = quantile(pointValues, ...
        cfg.experiments.aggregation.medianQuantile);
end
pointMedianSinrDb = 10 * log10(pointMedianLinear);
overallMedianLinear = quantile(sinrLinear(:), ...
    cfg.experiments.aggregation.medianQuantile);
minimumPointMedianSinrDb = min(pointMedianSinrDb);
record = emptyRecord();
record.method = method;
record.stage = stage;
record.parameterName = parameterName;
record.parameterValue = parameterValue;
record.minimumPointMedianSinrDb = minimumPointMedianSinrDb;
record.overallMedianSinrDb = 10 * log10(overallMedianLinear);
record.meanPointMedianSinrDb = mean(pointMedianSinrDb);
record.targetMet = minimumPointMedianSinrDb >= ...
    cfg.experiments.classicTuning.targetMinimumMedianSinrDb;
record.validCandidate = true;
record.epsilonS = calibration.epsilonS;
record.runtimeSec = toc(timerValue);
record.jitterRmsDeg = jitterPoints(:);
record.pointMedianSinrDb = pointMedianSinrDb;
end

function record = emptyRecord()
%EMPTYRECORD 返回字段固定的空候选记录，便于结构数组追加。
record = struct( ...
    'method', "", ...
    'stage', "", ...
    'parameterName', "", ...
    'parameterValue', NaN, ...
    'minimumPointMedianSinrDb', NaN, ...
    'overallMedianSinrDb', NaN, ...
    'meanPointMedianSinrDb', NaN, ...
    'targetMet', false, ...
    'validCandidate', false, ...
    'errorIdentifier', "", ...
    'errorMessage', "", ...
    'epsilonS', NaN, ...
    'runtimeSec', NaN, ...
    'selectedForStage', false, ...
    'jitterRmsDeg', zeros(0, 1), ...
    'pointMedianSinrDb', zeros(0, 1));
end

function output = recordsToTable(records)
%RECORDSTOTABLE 提取适合CSV排序和人工审阅的标量候选指标。
output = table( ...
    string({records.method}).', ...
    string({records.stage}).', ...
    string({records.parameterName}).', ...
    [records.parameterValue].', ...
    [records.minimumPointMedianSinrDb].', ...
    [records.overallMedianSinrDb].', ...
    [records.meanPointMedianSinrDb].', ...
    logical([records.targetMet].'), ...
    logical([records.validCandidate].'), ...
    string({records.errorIdentifier}).', ...
    string({records.errorMessage}).', ...
    [records.epsilonS].', ...
    [records.runtimeSec].', ...
    logical([records.selectedForStage].'), ...
    'VariableNames', {'method', 'stage', 'parameterName', ...
        'parameterValue', 'minimumPointMedianSinrDb', ...
        'overallMedianSinrDb', 'meanPointMedianSinrDb', 'targetMet', ...
        'validCandidate', 'errorIdentifier', 'errorMessage', ...
        'epsilonS', 'runtimeSec', 'selectedForStage'});
end
