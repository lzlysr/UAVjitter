function result = runExp04(cfg)
%RUNEXP04 实验4：评估默认动态场景下的逐周期稳定性。
%   本实验保留完整[试次×周期×方法]数据，既观察跨试次中位时序，也把
%   全部有限输出用于经验CDF、低分位和低于阈值的概率计算。

experimentTimer = tic;
[cfg, calibration] = uav.experiment.prepare(cfg);
experimentIndex = 4;
trialCount = cfg.monteCarlo.nTrials;
periodCount = cfg.experiments.periodCounts.dynamicStability;
methodCount = numel(cfg.experiments.methodNames);
[raw, seeds] = uav.experiment.collectMethods( ...
    cfg, experimentIndex, 1, periodCount);
sinrValues = reshape(raw.sinrLinear, trialCount * periodCount, methodCount);
% 动态相关性由summarizeTrials在bootstrap时按完整试次簇保留。
bootstrapSubstream = uav.experiment.substream( ...
    cfg, experimentIndex, 1, 0, 0, "bootstrap");
sinrSummary = uav.experiment.summarizeTrials( ...
    raw.sinrLinear, cfg, bootstrapSubstream);
gainSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.desiredGain, [], methodCount), cfg);
leakageSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.interferenceLeakage, [], methodCount), cfg);
runtimeSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.runtimeSec, [], methodCount), cfg);
outageThresholdLinear = 10^(cfg.experiments.outageThresholdDb / 10);
% 先把配置dB阈值转回线性域，再与原始SINR比较。
outageProbability = sum(sinrValues < outageThresholdLinear, 1) / size(sinrValues, 1);
periodMedianLinear = squeeze(median(raw.sinrLinear, 1));
periodMedianDb = 10 * log10(periodMedianLinear);
periodMedianGain = squeeze(median(raw.desiredGain, 1));
periodMedianLeakage = squeeze(median(raw.interferenceLeakage, 1));
summaryTable = table(cfg.experiments.methodNames.', sinrSummary.lowDb.', ...
    outageProbability.', gainSummary.median.', leakageSummary.median.', ...
    runtimeSummary.mean.', runtimeSummary.p95.', ...
    'VariableNames', {'method', 'p05SinrDb', 'outageProbability', ...
    'medianDesiredGain', 'medianInterferenceLeakage', ...
    'meanRuntimeSec', 'p95RuntimeSec'});

fig = uav.plot.newFigure(cfg);
% 五个面板：SINR时序、经验CDF、期望增益、干扰泄漏和运行时间。
layout = tiledlayout(fig, 'flow');
nexttile(layout);
timeMs = (0:periodCount - 1).' * cfg.timeline.dtSec * 1e3;
plot(timeMs, periodMedianDb, 'LineWidth', cfg.plot.lineWidth);
xlabel('Time (ms)', 'FontSize', cfg.plot.fontSize);
ylabel('Across-trial median SINR (dB)', 'FontSize', cfg.plot.fontSize); grid on;
set(gca, 'FontSize', cfg.plot.fontSize, 'LineWidth', cfg.plot.lineWidth-1);
legend(cellstr(cfg.experiments.methodNames), 'Location', 'best', ...
    'FontSize', cfg.plot.fontSize);
nexttile(layout); hold on;
for methodIndex = 1:methodCount
    % CDF仅在展示时将线性SINR转换为dB。
    [cdfX, cdfProbability] = uav.plot.finiteCdf( ...
        10 * log10(sinrValues(:, methodIndex)));
    plot(cdfX, cdfProbability, 'LineWidth', cfg.plot.lineWidth);
end
xlabel('Output SINR (dB)', 'FontSize', cfg.plot.fontSize);
ylabel('Empirical CDF', 'FontSize', cfg.plot.fontSize); grid on;
set(gca, 'FontSize', cfg.plot.fontSize, 'LineWidth', cfg.plot.lineWidth-1);
legend(cellstr(cfg.experiments.methodNames), 'Location', 'best', ...
    'FontSize', cfg.plot.fontSize);
nexttile(layout);
plot(timeMs, periodMedianGain, 'LineWidth', cfg.plot.lineWidth);
xlabel('Time (ms)', 'FontSize', cfg.plot.fontSize);
ylabel('Across-trial median desired gain', 'FontSize', cfg.plot.fontSize); grid on;
set(gca, 'FontSize', cfg.plot.fontSize, 'LineWidth', cfg.plot.lineWidth-1);
legend(cellstr(cfg.experiments.methodNames), 'Location', 'best', ...
    'FontSize', cfg.plot.fontSize);
nexttile(layout);
plot(timeMs, 10 * log10(max(periodMedianLeakage, realmin)), ...
    'LineWidth', cfg.plot.lineWidth);
xlabel('Time (ms)', 'FontSize', cfg.plot.fontSize);
ylabel('Across-trial median leakage (dB)', 'FontSize', cfg.plot.fontSize); grid on;
set(gca, 'FontSize', cfg.plot.fontSize, 'LineWidth', cfg.plot.lineWidth-1);
legend(cellstr(cfg.experiments.methodNames), 'Location', 'best', ...
    'FontSize', cfg.plot.fontSize);
nexttile(layout);
runtimeBars = [runtimeSummary.mean.', runtimeSummary.p95.'];
bar(categorical(cfg.experiments.methodNames, cfg.experiments.methodNames, ...
    'Ordinal', true), runtimeBars);
ylabel('Runtime per period (s)', 'FontSize', cfg.plot.fontSize); grid on;
legend({'mean', '95th percentile'}, 'Location', 'best', ...
    'FontSize', cfg.plot.fontSize);
set(gca, 'TickLabelInterpreter', 'none', 'FontSize', cfg.plot.fontSize);
title(layout, 'Dynamic stability diagnostics');

result = struct('experimentName', "exp04_dynamic_stability", ...
    'calibration', calibration, 'methodNames', cfg.experiments.methodNames, ...
    'seedScheme', seeds, 'raw', raw, ...
    'summary', struct('sinr', sinrSummary, ...
        'periodMedianSinrLinear', periodMedianLinear, ...
        'periodMedianSinrDb', periodMedianDb, ...
        'periodMedianDesiredGain', periodMedianGain, ...
        'periodMedianInterferenceLeakage', periodMedianLeakage, ...
        'outageThresholdDb', cfg.experiments.outageThresholdDb, ...
        'outageProbability', outageProbability, ...
        'desiredGain', gainSummary, 'interferenceLeakage', leakageSummary, ...
        'runtime', runtimeSummary));
actualCounts = struct('trials', trialCount, 'periods', periodCount, ...
    'methods', methodCount);
result = uav.experiment.finalize(result, summaryTable, fig, cfg, ...
    actualCounts, experimentTimer);
end
