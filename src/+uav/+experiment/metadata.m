function metadata = metadata(cfg, experimentName, actualCounts, runtimeSec)
%METADATA Capture reproducibility and environment metadata for one result.

rootDir = cfg.output.rootDir;
[commitStatus, commitText] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD', rootDir));
[dirtyStatus, dirtyText] = system(sprintf( ...
    'git -C "%s" status --porcelain', rootDir));
if commitStatus ~= 0
    gitCommit = "unavailable";
else
    gitCommit = string(strtrim(commitText));
    if dirtyStatus ~= 0
        gitCommit = gitCommit + "-status-unavailable";
    elseif strlength(strtrim(string(dirtyText))) > 0
        gitCommit = gitCommit + "-dirty";
    end
end
toolboxData = ver;
metadata = struct( ...
    'gitCommit', gitCommit, ...
    'matlabVersion', string(version), ...
    'toolboxes', toolboxData, ...
    'profile', cfg.profile, ...
    'experimentName', string(experimentName), ...
    'baseSeed', cfg.random.baseSeed, ...
    'generatedAt', string(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSSXXX')), ...
    'codeVersion', cfg.experiments.codeVersion, ...
    'actualCounts', actualCounts, ...
    'seedScheme', cfg.experiments.substreams, ...
    'runtimeSec', runtimeSec);
end
