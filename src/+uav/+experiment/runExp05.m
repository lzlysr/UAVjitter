function result = runExp05(cfg)
%RUNEXP05 Run fixed one-switch-at-a-time temporal ablations.

experimentTimer = tic;
[cfg, calibration] = uav.experiment.prepare(cfg);
experimentIndex = 5;
trialCount = cfg.monteCarlo.nTrials;
periodCount = cfg.experiments.periodCounts.ablation;
variantCount = numel(cfg.experiments.ablationNames);
[raw, seeds, switchDiagnostics] = uav.experiment.collectVariants( ...
    cfg, experimentIndex, periodCount);
bootstrapSubstream = uav.experiment.substream( ...
    cfg, experimentIndex, 1, 0, 0, "bootstrap");
sinrSummary = uav.experiment.summarizeTrials( ...
    raw.sinrLinear, cfg, bootstrapSubstream);
gainSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.desiredGain, [], variantCount), cfg);
leakageSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.interferenceLeakage, [], variantCount), cfg);
nmseSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.incmNmse, [], variantCount), cfg);
runtimeSummary = uav.experiment.summarizeFinite( ...
    reshape(raw.runtimeSec, [], variantCount), cfg);
summaryTable = table(cfg.experiments.ablationNames.', ...
    switchDiagnostics.switchDeltaFields.', sinrSummary.medianDb.', ...
    sinrSummary.lowDb.', gainSummary.median.', leakageSummary.median.', ...
    nmseSummary.median.', runtimeSummary.median.', ...
    'VariableNames', {'variant', 'changedField', 'medianSinrDb', ...
    'p05SinrDb', 'medianDesiredGain', 'medianInterferenceLeakage', ...
    'medianIncmNmse', 'medianRuntimeSec'});

fig = uav.plot.newFigure(cfg);
layout = tiledlayout(fig, 'flow');
nexttile(layout);
ablationPositions = 1:variantCount;
ablationLabels = replace(cfg.experiments.ablationNames, "_", " ");
bar(ablationPositions, sinrSummary.medianDb);
xticks(ablationPositions); xticklabels(ablationLabels); xtickangle(15);
ylabel('Median output SINR (dB)'); grid on;
set(gca, 'TickLabelInterpreter', 'none');
nexttile(layout);
bar(ablationPositions, sinrSummary.lowDb);
xticks(ablationPositions); xticklabels(ablationLabels); xtickangle(15);
ylabel('5th-percentile output SINR (dB)'); grid on;
set(gca, 'TickLabelInterpreter', 'none');
title(layout, 'Paired temporal-method ablations');

result = struct('experimentName', "exp05_ablation", ...
    'calibration', calibration, 'variantNames', cfg.experiments.ablationNames, ...
    'seedScheme', seeds, 'raw', raw, ...
    'switchDiagnostics', switchDiagnostics, ...
    'summary', struct('sinr', sinrSummary, 'desiredGain', gainSummary, ...
        'interferenceLeakage', leakageSummary, 'incmNmse', nmseSummary, ...
        'runtime', runtimeSummary));
actualCounts = struct('trials', trialCount, 'periods', periodCount, ...
    'variants', variantCount);
result = uav.experiment.finalize(result, summaryTable, fig, cfg, ...
    actualCounts, experimentTimer);
end
