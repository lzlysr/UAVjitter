function [raw, seeds, switchDiagnostics] = collectVariants( ...
        cfg, experimentIndex, periodCount)
%COLLECTVARIANTS Generate paired observations for the fixed temporal ablations.

trialCount = cfg.monteCarlo.nTrials;
variantCount = numel(cfg.experiments.ablationNames);
raw = struct( ...
    'sinrLinear', zeros(trialCount, periodCount, variantCount), ...
    'desiredGain', zeros(trialCount, periodCount, variantCount), ...
    'interferenceLeakage', zeros(trialCount, periodCount, variantCount), ...
    'incmNmse', zeros(trialCount, periodCount, variantCount), ...
    'runtimeSec', zeros(trialCount, periodCount, variantCount), ...
    'snapshotSignatures', zeros(trialCount, periodCount, variantCount, 4));
seeds = struct( ...
    'scenarioSubstreams', zeros(trialCount, 1), ...
    'snapshotSubstreams', zeros(trialCount, periodCount));
switchDiagnostics = struct();
for trialIndex = 1:trialCount
    scenarioSubstream = uav.experiment.substream(cfg, experimentIndex, ...
        1, trialIndex, 0, "scenario");
    seeds.scenarioSubstreams(trialIndex) = scenarioSubstream;
    scenario = uav.scenario.generate(cfg, ...
        uav.util.makeStream(cfg.random.baseSeed, scenarioSubstream));
    variantStates = [];
    for periodIndex = 1:periodCount
        snapshotSubstream = uav.experiment.substream(cfg, experimentIndex, ...
            1, trialIndex, periodIndex, "snapshot");
        seeds.snapshotSubstreams(trialIndex, periodIndex) = snapshotSubstream;
        obs = uav.scenario.generatePeriod(cfg, scenario, periodIndex, ...
            uav.util.makeStream(cfg.random.baseSeed, snapshotSubstream));
        [record, variantStates] = uav.experiment.runVariants(obs, variantStates, cfg);
        raw.sinrLinear(trialIndex, periodIndex, :) = record.sinrLinear;
        raw.desiredGain(trialIndex, periodIndex, :) = record.desiredGain;
        raw.interferenceLeakage(trialIndex, periodIndex, :) = ...
            record.interferenceLeakage;
        raw.incmNmse(trialIndex, periodIndex, :) = record.incmNmse;
        raw.runtimeSec(trialIndex, periodIndex, :) = record.runtimeSec;
        raw.snapshotSignatures(trialIndex, periodIndex, :, :) = ...
            reshape(record.snapshotSignatures, 1, 1, variantCount, 4);
        if trialIndex == 1 && periodIndex == 1
            switchDiagnostics = struct( ...
                'variantNames', record.variantNames, ...
                'switchDeltaFields', record.switchDeltaFields, ...
                'effectiveIncmConfigs', {record.effectiveIncmConfigs}, ...
                'epsilonS', record.epsilonS, ...
                'gamma', record.gamma);
        end
    end
end
end
