function [RinHat,diagnostics]=caponPoint(obs,cfg)
%CAPONPOINT 观测找干扰峰、直接读峰点功率、离散源外积求和并加估计噪声。
%   不乘网格面积，不做NNLS、连续方向细化或期望导向校正。
%   峰点Capon值可能含残余噪声/其它源贡献，本基线不额外扣除它们。
front=uav.spectrum.interferenceCandidates(obs,cfg);
A=front.manifold;
[powers,powerDiagnostics]=uav.spectrum.caponAtDirections(obs.Rx,A,cfg.incm.caponPoint.powerLoadingRatio);
RinHat=(A.*powers.')*A'+front.noisePower*eye(cfg.derived.M);
RinHat=(RinHat+RinHat')/2;
diagnostics=struct('method',"incm_capon_point",'interfererCandidateNodes',front.nodes, ...
    'candidateManifold',A,'caponPowers',powers,'noisePower',front.noisePower, ...
    'noiseSource',front.noiseSource,'noiseDiagnostics',front.noiseDiagnostics, ...
    'peakSelection',front.selection,'candidateGridSize',front.candidateGridSize, ...
    'candidateLoading',front.candidateLoading,'powerSpectrum',powerDiagnostics, ...
    'powerFittingApplied',false,'refinementApplied',false, ...
    'desiredProjectionApplied',false,'desiredSteeringCorrectionApplied',false,'usedTruth',false);
end
