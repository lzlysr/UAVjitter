function [scanManifold, scanWeights, diagnostics] = ...
        guLeshem2012UpaQuadrature(cfg)
%GULESHEM2012UPAQUADRATURE 构造原论文式(7)的二维UPA直接扩展求积。
%   该函数只把一维d(theta)替换为当前工程的二维方向余弦面积元
%   d(xi_x)d(xi_y)，不加入功率校准、Jacobian、动态排除区或非均匀求积。
%   因此它是需要接受网格收敛检验的迁移对象，而不是原论文既有结论。

if ~isstruct(cfg) || ~isfield(cfg, 'derived') || ...
        ~isfield(cfg.derived, 'spectrumGrid')
    error('uav:spectrum:MissingUpaGrid', ...
        'A validated UPA spectrum grid is required.');
end
grid = cfg.derived.spectrumGrid;
nodes = [grid.xiX(:), grid.xiY(:)];
included = reshape(uav.spectrum.admissibleDirections(nodes, cfg), ...
    size(grid.xiX)) & grid.visibleMask;
linearIndices = find(included);
[found, cachedColumns] = ismember(linearIndices, grid.visibleLinearIndices);
if ~all(found) || isempty(cachedColumns)
    error('uav:spectrum:InvalidUpaComplement', ...
        'The UPA complement sector must contain cached visible-grid nodes.');
end
scanManifold = grid.manifold(:, cachedColumns);
scanWeights = grid.cellArea * ones(1, numel(cachedColumns));
diagnostics = struct( ...
    'integrationMeasure', "direction-cosine-area", ...
    'includedMask', included, ...
    'linearIndices', linearIndices, ...
    'cellArea', grid.cellArea, ...
    'representedArea', sum(scanWeights), ...
    'scanPointCount', numel(cachedColumns), ...
    'usesDynamicSector', false, ...
    'usesTemporalSpectrum', false, ...
    'usesStructureEnhancement', false);
end
